import { render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { useState } from 'react'
import { describe, expect, it } from 'vitest'
import { errorResponse, mockFetch, ndjson, openStream } from '../test/fetchMock'
import { config, paper } from '../test/fixtures'
import type { AppConfig, PaperDetail } from '../types'
import SummaryPanel from './SummaryPanel'

const SUMMARY = {
  summary: '**TL;DR**: Attention replaces recurrence.\n\n- Faster training\n- Better BLEU',
  summary_model: 'claude-opus-5 via Claude Code',
  summary_context: 'full_text' as const,
  summary_created_at: '2026-10-02T09:30:00Z',
}

// Holds the paper like the reader does, so a finished summary shows up.
function Reader({ initial, llm, model }: { initial: PaperDetail; llm: AppConfig | null; model: string | null }) {
  const [current, setCurrent] = useState(initial)
  return <SummaryPanel paper={current} llm={llm} model={model} onSummary={(f) => setCurrent((p) => ({ ...p, ...f }))} />
}

function setup(initial = paper({ id: 7, full_text_status: 'ok', has_pdf: true }), llm: AppConfig | null = config(), model: string | null = 'opus') {
  const api = mockFetch()
  const user = userEvent.setup()
  render(<Reader initial={initial} llm={llm} model={model} />)
  return { api, user }
}

describe('SummaryPanel', () => {
  it('says what the summary will be based on', () => {
    setup()
    expect(screen.getByText('No summary yet. The assistant reads the text extracted from the PDF.')).toBeInTheDocument()
  })

  it('warns when only the abstract can be summarized', () => {
    setup(paper({ full_text_status: 'unavailable' }))
    expect(
      screen.getByText('No summary yet. The PDF text is not available, so the summary uses only the abstract.'),
    ).toBeInTheDocument()
  })

  it('streams a new summary and then shows the saved one', async () => {
    const { api, user } = setup()
    const stream = openStream()
    api.on('POST', '/api/papers/7/summary', stream.response)

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))
    expect(screen.getByRole('button', { name: 'Generating…' })).toBeDisabled()
    expect(screen.getByText(/Reading the paper and writing a summary/)).toBeInTheDocument()

    stream.send({ type: 'meta', context: 'full_text', truncated: false })
    stream.send({ type: 'text', text: '**TL;DR**: Attention ' })
    expect(await screen.findByText(/Attention/)).toBeInTheDocument()

    stream.send({ type: 'text', text: 'replaces recurrence.' })
    stream.send({ type: 'done', paper: paper({ id: 7, ...SUMMARY }) })
    stream.close()

    expect(await screen.findByRole('button', { name: 'Regenerate' })).toBeEnabled()
    expect(screen.getByText('TL;DR').tagName).toBe('STRONG') // rendered as Markdown
    expect(screen.getByRole('list')).toHaveTextContent('Faster training')
    expect(screen.getByText(/Generated by claude-opus-5 via Claude Code from the full text/)).toBeInTheDocument()
  })

  it('asks for the model chosen in the reader', async () => {
    const { api, user } = setup(undefined, config(), 'sonnet')
    api.on('POST', '/api/papers/7/summary', ndjson([{ type: 'done', paper: paper({ id: 7, ...SUMMARY }) }]))

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))

    await waitFor(() => expect(api.callsTo('POST', '/api/papers/7/summary')).toHaveLength(1))
    expect(api.callsTo('POST', '/api/papers/7/summary')[0].query.get('model')).toBe('sonnet')
  })

  it('labels a summary written from the abstract only', () => {
    setup(paper({ ...SUMMARY, summary_context: 'abstract' }))
    expect(screen.getByText(/from the abstract only/)).toBeInTheDocument()
  })

  it('shows the error and keeps the previous summary when regenerating fails', async () => {
    const { api, user } = setup(paper({ id: 7, ...SUMMARY }))
    api.on(
      'POST',
      '/api/papers/7/summary',
      ndjson([
        { type: 'meta', context: 'full_text', truncated: false },
        { type: 'text', text: 'Partial new text' },
        { type: 'error', message: 'Claude Code usage limit reached (resets 5pm).' },
      ]),
    )

    await user.click(screen.getByRole('button', { name: 'Regenerate' }))

    expect(await screen.findByText('Claude Code usage limit reached (resets 5pm).')).toBeInTheDocument()
    expect(screen.getByText('TL;DR')).toBeInTheDocument()
    expect(screen.queryByText('Partial new text')).not.toBeInTheDocument()
  })

  it('shows an error returned before streaming starts', async () => {
    const { api, user } = setup()
    api.on('POST', '/api/papers/7/summary', errorResponse(422, 'Unknown model “gpt-4o”.'))

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))

    expect(await screen.findByText('Unknown model “gpt-4o”.')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Generate summary' })).toBeEnabled()
  })

  it('notices a stream that ends without a result', async () => {
    const { api, user } = setup()
    api.on('POST', '/api/papers/7/summary', ndjson([{ type: 'meta', context: 'full_text', truncated: false }]))

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))

    expect(await screen.findByText('The response ended unexpectedly. Please try again.')).toBeInTheDocument()
  })

  it.each([
    [true, true],
    [false, false],
  ])('tells the user when a long paper was cut off (cut off: %s)', async (truncated, noteShown) => {
    const { api, user } = setup()
    const stream = openStream()
    api.on('POST', '/api/papers/7/summary', stream.response)

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))
    stream.send({ type: 'meta', context: 'full_text', truncated })
    stream.send({ type: 'text', text: 'The summary so far.' })

    expect(await screen.findByText('The summary so far.')).toBeInTheDocument() // the meta event was handled
    const note = screen.queryByText('The paper is very long, so only its first part was sent to the model.')
    expect(note !== null).toBe(noteShown)
  })

  it('discards text from a model that was replaced mid-answer', async () => {
    const { api, user } = setup()
    const stream = openStream()
    api.on('POST', '/api/papers/7/summary', stream.response)

    await user.click(screen.getByRole('button', { name: 'Generate summary' }))
    stream.send({ type: 'text', text: 'First attempt' })
    expect(await screen.findByText('First attempt')).toBeInTheDocument()
    stream.send({ type: 'reset' })
    stream.send({ type: 'text', text: 'Second attempt' })

    expect(await screen.findByText('Second attempt')).toBeInTheDocument()
    expect(screen.queryByText(/First attempt/)).not.toBeInTheDocument()
    stream.close()
  })

  it('explains how to fix an unavailable LLM and disables the button', () => {
    setup(undefined, config({ llm_ready: false, llm_hint: 'Run `claude auth login` in a terminal, then come back.' }))

    expect(screen.getByText('Summaries and Q&A are unavailable.')).toBeInTheDocument()
    expect(screen.getByText('claude auth login').tagName).toBe('CODE')
    expect(screen.getByRole('button', { name: 'Generate summary' })).toBeDisabled()
  })
})
