import { expect, test, type Page } from '@playwright/test'
import {
  SAMPLE,
  ask,
  isHighlighted,
  offsetInPdfView,
  paperId,
  resetApp,
  samplePaper,
  sectionItem,
  textHeightInPdfView,
} from './support/app'

test.beforeEach(async ({ request }) => {
  await resetApp(request)
})

async function uploadSample(page: Page, variant: 'sample' | 'sections' = 'sample') {
  await page.goto('/#/library')
  await page.locator('input[type="file"]').setInputFiles(samplePaper(`${variant}.pdf`, variant))
  await expect(page).toHaveURL(/#\/paper\/\d+$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(SAMPLE.title)
}

// PDF.js has loaded the stored file and laid out the text of the page that holds `text`.
async function expectPdfShows(page: Page, pages: number, text: string) {
  await expect(page.getByText(`Page 1 of ${pages}`)).toBeVisible()
  await expect(page.locator('.pdf-scroll').getByText(text)).toBeAttached()
}

test('upload a PDF: its metadata is extracted and the PDF is shown', async ({ page }) => {
  await uploadSample(page)

  const header = page.locator('.reader-head')
  await expect(header.getByText(SAMPLE.authors.join(', '), { exact: true })).toBeVisible()
  await expect(header.getByText(String(SAMPLE.year), { exact: true })).toBeVisible()
  await expect(header.getByText('✓ In library')).toBeVisible()
  // The viewer shows the stored file, down to the text of page 2.
  await expectPdfShows(page, 2, SAMPLE.bodyMarker)

  // The outline comes from the PDF's headings.
  for (const heading of SAMPLE.sections.slice(1)) {
    await expect(page.getByRole('button', { name: new RegExp(`^${heading}`) })).toBeVisible()
  }

  await page.getByRole('tab', { name: 'Details' }).click()
  const details = page.getByRole('article')
  await expect(details.getByText(SAMPLE.abstract, { exact: true })).toBeVisible()
  await expect(details.getByText('Uploaded PDF')).toBeVisible()

  await page.getByRole('link', { name: 'Library', exact: true }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toContainText(SAMPLE.title)
})

test('generate a summary of the uploaded paper', async ({ page }) => {
  await uploadSample(page)

  await page.getByRole('tab', { name: 'Summary' }).click()
  await page.getByRole('button', { name: 'Generate summary' }).click()

  const summary = page.locator('.panel').filter({ has: page.getByRole('heading', { name: 'Summary' }) })
  // The fake Claude Code reports what it was given: the paper's title, and its text to the last page.
  await expect(summary).toContainText(`about “${SAMPLE.title}”`)
  await expect(summary).toContainText(`The paper text ends with “${SAMPLE.textEnd}”`)
  await expect(summary.getByText('Fake answer')).toHaveJSProperty('tagName', 'STRONG') // rendered Markdown
  await expect(summary.getByText(/Generated by claude-fake-opus via Claude Code from the full text/)).toBeVisible()
  await expect(summary.getByRole('button', { name: 'Regenerate' })).toBeEnabled()

  await page.reload()
  await page.getByRole('tab', { name: 'Summary' }).click()
  await expect(page.getByText(/Generated by claude-fake-opus via Claude Code from the full text/)).toBeVisible()
  await expect(page.getByText(`The paper text ends with “${SAMPLE.textEnd}”`, { exact: false })).toBeVisible()
})

test('ask questions about the uploaded paper, with follow-ups', async ({ page }) => {
  await uploadSample(page)
  const log = page.locator('.chat-log')
  // A saved answer shows which model wrote it.
  const savedAnswers = log.getByText('claude-fake-opus via Claude Code')

  await ask(page, 'What datasets are used?')
  await expect(log).toContainText('to “What datasets are used?”')
  await expect(log).toContainText('Earlier questions quoted: 0.')
  await expect(savedAnswers).toHaveCount(1)

  await page.getByRole('button', { name: 'What are the major limitations?' }).click()
  await expect(log).toContainText('to “What are the major limitations?”')
  await expect(log).toContainText('Earlier questions quoted: 1.') // the first question went with it
  await expect(savedAnswers).toHaveCount(2)

  await page.reload()
  await expect(page.locator('.chat-log .bubble')).toHaveCount(4)

  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Clear conversation' }).click()
  await expect(page.locator('.chat-log')).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: 'What datasets are used?' })).toBeEnabled()
  await expect(page.locator('.chat-log')).toHaveCount(0)
})

test('a failed answer is reported and nothing is saved', async ({ page, request }) => {
  await uploadSample(page)

  // The fake CLI fails when a prompt contains this marker.
  await ask(page, '[[fake:error]] Why?')

  await expect(page.getByText('Claude Code reported an error: Simulated failure')).toBeVisible()
  await expect(page.getByPlaceholder('Ask about this paper (Enter to send)')).toHaveValue('[[fake:error]] Why?')
  const chat = await request.get(`/api/papers/${paperId(page)}/chat`)
  expect(await chat.json()).toEqual([])
})

test('summarize the sections and jump to one', async ({ page }) => {
  await uploadSample(page, 'sections') // five pages, one section heading near the top of each
  await expectPdfShows(page, 5, SAMPLE.title.split(' ').slice(0, 4).join(' '))

  await page.getByRole('button', { name: 'Summarize sections' }).click()
  await expect(page.getByText('Fake summary of the section 3 Experiments.')).toBeVisible()
  await expect(page.getByText('by claude-fake-opus via Claude Code')).toBeVisible()

  await page.getByRole('button', { name: /^3 Experiments/ }).click()

  // The heading is scrolled to the top of the view, its page is the current one,
  // and it is highlighted as the section being read.
  await expect.poll(() => offsetInPdfView(page, '3 Experiments')).toBeLessThan(60)
  expect(await offsetInPdfView(page, '3 Experiments')).toBeGreaterThanOrEqual(0)
  await expect(page.getByText('Page 3 of 5')).toBeVisible()
  await expect.poll(() => isHighlighted(sectionItem(page, '3 Experiments'))).toBe(true)
  for (const other of SAMPLE.sectionPages.filter((title) => title !== '3 Experiments')) {
    expect(await isHighlighted(sectionItem(page, other))).toBe(false)
  }
})

test('zooming keeps the reading position', async ({ page }) => {
  await uploadSample(page, 'sections')
  await expectPdfShows(page, 5, SAMPLE.title.split(' ').slice(0, 4).join(' '))
  await page.getByRole('button', { name: /^4 Results/ }).click()
  await expect.poll(() => offsetInPdfView(page, '4 Results')).toBeLessThan(60)
  const before = await offsetInPdfView(page, '4 Results')
  const heightAtFitWidth = await textHeightInPdfView(page, '4 Results')

  for (const [control, zoom] of [['Zoom in', 125], ['Zoom in', 150], ['Zoom out', 125], ['Fit width', 100]] as const) {
    await page.getByRole('button', { name: control }).click()
    // Wait for the new zoom level: its label, and the page drawn at the new size (PDF.js
    // redraws a page's text a moment after the page itself is resized).
    await expect(page.locator('.pdf-toolbar').getByText(`${zoom}%`, { exact: true })).toBeVisible()
    await expect.poll(async () => (await textHeightInPdfView(page, '4 Results')) / heightAtFitWidth).toBeCloseTo(zoom / 100, 1)
    // The same place stays at the top of the view, whatever the page size.
    await expect.poll(async () => Math.abs((await offsetInPdfView(page, '4 Results')) - before)).toBeLessThan(25)
    await expect(page.getByText('Page 4 of 5')).toBeVisible()
  }
})

test('fix the extracted metadata', async ({ page }) => {
  await uploadSample(page)
  await page.getByRole('tab', { name: 'Details' }).click()
  await page.getByRole('button', { name: 'Edit details' }).click()

  await page.getByRole('textbox', { name: 'Title' }).fill('Retrieval Keeps LLMs Factual')
  await page.getByRole('textbox', { name: /Authors/ }).fill('Alice Smith\nCarol White')
  await page.getByRole('button', { name: 'Save changes' }).click()

  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Retrieval Keeps LLMs Factual')
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Retrieval Keeps LLMs Factual')
  await expect(page.locator('.reader-head').getByText('Alice Smith, Carol White', { exact: true })).toBeVisible()
})

test('files that are not PDFs are refused', async ({ page }) => {
  await page.goto('/#/library')
  await expect(page.getByText('0 papers')).toBeVisible()

  await page.locator('input[type="file"]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('hi') })
  await expect(page.getByText('Please choose a PDF file.')).toBeVisible()

  // Named .pdf, but not a PDF: the backend refuses it.
  await page.locator('input[type="file"]').setInputFiles({
    name: 'fake.pdf',
    mimeType: 'application/pdf',
    buffer: Buffer.from('<html>not a pdf</html>'),
  })
  await expect(page.getByText('The file is not a PDF.')).toBeVisible()
  await expect(page.getByText('0 papers')).toBeVisible()
})
