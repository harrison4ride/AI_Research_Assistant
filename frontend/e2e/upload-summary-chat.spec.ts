import { expect, test, type Page } from '@playwright/test'
import { SAMPLE, ask, emptyLibrary, samplePaper } from './support/app'

test.beforeEach(async ({ request }) => {
  await emptyLibrary(request)
})

async function uploadSample(page: Page) {
  await page.goto('/#/library')
  await page.locator('input[type="file"]').setInputFiles(samplePaper())
  await expect(page).toHaveURL(/#\/paper\/\d+$/)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(SAMPLE.title)
}

test('upload a PDF: its metadata is extracted and the PDF is shown', async ({ page }) => {
  await uploadSample(page)

  const header = page.locator('.reader-head')
  await expect(header).toContainText(SAMPLE.authors)
  await expect(header).toContainText(SAMPLE.year)
  await expect(header.getByText('✓ In library')).toBeVisible()
  await expect(page.getByText('Page 1 of 2')).toBeVisible() // PDF.js rendered the stored file
  await expect(page.locator('.react-pdf__Page canvas').first()).toBeVisible()

  // The outline comes from the PDF's headings.
  for (const heading of ['1 Introduction', '2 Method', '3 Experiments', '4 Conclusion']) {
    await expect(page.getByRole('button', { name: new RegExp(heading) })).toBeVisible()
  }

  await page.getByRole('tab', { name: 'Details' }).click()
  const details = page.getByRole('article')
  await expect(details.getByText(new RegExp(SAMPLE.abstractStart))).toBeVisible()
  await expect(details.getByText('Uploaded PDF')).toBeVisible()

  await page.getByRole('link', { name: 'Library', exact: true }).click()
  await expect(page.getByRole('article')).toContainText(SAMPLE.title)
})

test('generate a summary of the uploaded paper', async ({ page }) => {
  await uploadSample(page)

  await page.getByRole('tab', { name: 'Summary' }).click()
  await page.getByRole('button', { name: 'Generate summary' }).click()

  const summary = page.locator('.panel').filter({ has: page.getByRole('heading', { name: 'Summary' }) })
  await expect(summary.getByText(`Fake summary of “${SAMPLE.title}”, written from the full text.`)).toBeVisible()
  await expect(summary.getByText('TL;DR')).toHaveJSProperty('tagName', 'STRONG')
  await expect(summary.getByText(/Generated by claude-fake-1 via Claude Code from the full text/)).toBeVisible()
  await expect(summary.getByRole('button', { name: 'Regenerate' })).toBeEnabled()

  await page.reload()
  await page.getByRole('tab', { name: 'Summary' }).click()
  await expect(page.getByText(`Fake summary of “${SAMPLE.title}”, written from the full text.`)).toBeVisible()
})

test('ask questions about the uploaded paper, with follow-ups', async ({ page }) => {
  await uploadSample(page)
  const log = page.locator('.chat-log')

  await ask(page, 'What datasets are used?')
  await expect(log).toContainText(`Fake answer to “What datasets are used?” about “${SAMPLE.title}”, from the full text.`)
  await expect(log).toContainText('Earlier questions in this conversation: 0.')

  await page.getByRole('button', { name: 'What are the major limitations?' }).click()
  await expect(log).toContainText('Fake answer to “What are the major limitations?”')
  await expect(log).toContainText('Earlier questions in this conversation: 1.')

  await page.reload()
  await expect(page.locator('.chat-log .bubble')).toHaveCount(4)

  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: 'Clear conversation' }).click()
  await expect(page.locator('.chat-log')).toHaveCount(0)
})

test('a failed answer is reported and nothing is saved', async ({ page }) => {
  await uploadSample(page)

  // The fake CLI fails when a prompt contains this marker.
  await ask(page, '[[fake:error]] Why?')

  await expect(page.getByText('Claude Code reported an error: Simulated failure')).toBeVisible()
  await expect(page.getByPlaceholder('Ask about this paper (Enter to send)')).toHaveValue('[[fake:error]] Why?')
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(SAMPLE.title)
  await expect(page.locator('.chat-log')).toHaveCount(0)
})

test('summarize the sections and jump to one', async ({ page }) => {
  await uploadSample(page)

  await page.getByRole('button', { name: 'Summarize sections' }).click()

  await expect(page.getByText('Fake summary of the section 2 Method.')).toBeVisible()
  await expect(page.getByText('by claude-fake-1 via Claude Code')).toBeVisible()
  await page.getByRole('button', { name: /3 Experiments/ }).click()
  await expect(page.getByText('Page 2 of 2')).toBeVisible()
})

test('fix the extracted metadata', async ({ page }) => {
  await uploadSample(page)
  await page.getByRole('tab', { name: 'Details' }).click()
  await page.getByRole('button', { name: 'Edit details' }).click()

  await page.getByRole('textbox', { name: 'Title' }).fill('Retrieval Keeps LLMs Factual')
  await page.getByRole('textbox', { name: /Authors/ }).fill('Alice Smith\nCarol White')
  await page.getByRole('button', { name: 'Save changes' }).click()

  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Retrieval Keeps LLMs Factual')
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Retrieval Keeps LLMs Factual')
  await expect(page.locator('.reader-head')).toContainText('Alice Smith, Carol White')
})

test('files that are not PDFs are refused', async ({ page }) => {
  await page.goto('/#/library')
  await expect(page.getByText('0 papers')).toBeVisible()

  await page.locator('input[type="file"]').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('hi') })
  await expect(page.getByText('Please choose a PDF file.')).toBeVisible()

  // Named .pdf, but not a PDF: the backend refuses it.
  await page.locator('input[type="file"]').setInputFiles({
    name: 'fake.pdf',
    mimeType: 'application/pdf',
    buffer: Buffer.from('<html>not a pdf</html>'),
  })
  await expect(page.getByText('The file is not a PDF.')).toBeVisible()
  await expect(page.getByText('0 papers')).toBeVisible()
})
